const { imageFromPage } = require('./link-image');
const path = require('node:path');
const names = ['announcement', 'products', 'community', 'calendar'];
let iconsPromise;
function iconsFor(app) {
  if (!iconsPromise)
    iconsPromise = load(app).catch((e) => {
      iconsPromise = undefined;
      throw e;
    });
  return iconsPromise;
}
async function load(app) {
  const existing = await app.emojis.fetch();
  const icons = {};
  for (const key of names) {
    const name = 'cheeseblack_' + key;
    const emoji =
      existing.find((e) => e.name === name) ||
      (await app.emojis.create({
        name,
        attachment: path.join(__dirname, '..', 'assets', key + '.png'),
      }));
    icons[key] = emoji.toString();
  }
  return icons;
}
async function thumbnail(link, fallback, request = fetch, readPage = imageFromPage) {
  if (!link) return fallback;
  try {
    const url = new URL(link);
    const place = /^(?:\/[a-z]{2}(?:-[a-z]{2})?)?\/games\/(\d+)(?:\/|$)/.exec(url.pathname)?.[1];
    if (!['www.roblox.com', 'roblox.com', 'm.roblox.com'].includes(url.hostname))
      return (await readPage(link)) || fallback;
    if (!place) return fallback;
    const json = async (url) => {
      const res = await request(url, { signal: AbortSignal.timeout(4000) });
      if (!res.ok) throw Error('Roblox ' + res.status);
      return res.json();
    };
    const { universeId } = await json('https://apis.roblox.com/universes/v1/places/' + place + '/universe');
    if (!/^\d+$/.test(String(universeId))) return fallback;
    const { data } = await json(
      'https://thumbnails.roblox.com/v1/games/icons?universeIds=' +
        universeId +
        '&size=150x150&format=Png&isCircular=false&returnPolicy=AutoGenerated',
    );
    const item = data?.[0];
    return item?.state === 'Completed' && /^https:\/\//.test(item.imageUrl) ? item.imageUrl : fallback;
  } catch {
    return fallback;
  }
}
module.exports = { thumbnail, iconsFor };
